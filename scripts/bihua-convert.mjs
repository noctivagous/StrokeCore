// --- minimal SVG path flattener (same as bihua-yong-diff.mjs) ---
function flattenPath(d, steps = 20) {
  const tokens = d.match(/[MLQCZ]|-?\d*\.?\d+/g);
  let i = 0, cmd = "", cur = [0, 0], start = null;
  const ring = [];
  const num = () => parseFloat(tokens[i++]);
  while (i < tokens.length) {
    if (/[MLQCZ]/.test(tokens[i])) cmd = tokens[i++];
    if (cmd === "M") { cur = [num(), num()]; start = cur; ring.push(cur); cmd = "L"; }
    else if (cmd === "L") { cur = [num(), num()]; ring.push(cur); }
    else if (cmd === "Q") {
      const c = [num(), num()]; const to = [num(), num()];
      for (let s = 1; s <= steps; s++) {
        const t = s / steps, u = 1 - t;
        ring.push([u * u * cur[0] + 2 * u * t * c[0] + t * t * to[0],
                   u * u * cur[1] + 2 * u * t * c[1] + t * t * to[1]]);
      }
      cur = to;
    } else if (cmd === "C") {
      const c1 = [num(), num()]; const c2 = [num(), num()]; const to = [num(), num()];
      for (let s = 1; s <= steps; s++) {
        const t = s / steps, u = 1 - t;
        ring.push([u ** 3 * cur[0] + 3 * u * u * t * c1[0] + 3 * u * t * t * c2[0] + t ** 3 * to[0],
                   u ** 3 * cur[1] + 3 * u * u * t * c1[1] + 3 * u * t * t * c2[1] + t ** 3 * to[1]]);
      }
      cur = to;
    } else if (cmd === "Z") { if (start) ring.push(start); }
  }
  return [ring];
}

function emitModule(rec, exportName) {
  const pt = (p) => `{ x: ${Math.round(p.x)}, y: ${Math.round(p.y)} }`;
  const strokes = rec.strokes.map((s) => {
    const segs = s.segments.map((g) =>
      `        { ${g.bafa ? `bafa: "${g.bafa}", ` : ""}form: "${g.form}", span: [${g.span[0]}, ${g.span[1]}] }`).join(",\n");
    const fit = s.fit
      ? `\n      fit: { confidence: ${s.fit.confidence}, validator: "${s.fit.validator}"${s.fit.failedRelations ? `, failedRelations: ${JSON.stringify(s.fit.failedRelations)}` : ""}, review: ${s.fit.review} },`
      : "";
    return `    {
      form: "${s.form}",
      spine: [${s.spine.map(pt).join(", ")}],
      pressure: [${s.pressure.join(", ")}],
      segments: [
${segs}
      ],
      provenance: "${s.provenance}",${fit}
    }`;
  }).join(",\n");
  return `// ${rec.char} (${rec.pinyin}, "${rec.gloss}") — FITTED DRAFT record.
// Generated by scripts/bihua-convert.mjs from Make Me a Hanzi medians
// (hanzi-writer-data 2.0.1, Arphic). Not authored: labels are the
// converter's, confidence and validator verdicts ride on each stroke,
// and strokes with review: true await a human look.

import type { BihuaCharacter } from "../../types.js";

export const ${exportName}: BihuaCharacter = {
  char: "${rec.char}",
  pinyin: "${rec.pinyin}",
  gloss: "${rec.gloss}",
  grid: 1024,
  pressureProvenance: "fitted",
  source: ${JSON.stringify(rec.source)},
  strokes: [
${strokes}
  ],
};
`;
}

mkdirSync(new URL("../src/bihua/characters/fitted/", import.meta.url), { recursive: true });

let totalStrokes = 0, reviewCount = 0, failCount = 0;
const queue = [];
console.log("char  strokes  IoU    review  labels");
for (const [ch, name, pinyin, gloss] of BATCH) {
  const data = JSON.parse(readFileSync(new URL(`./fixtures/hanzi-writer/${ch}.json`, import.meta.url), "utf8"));
  const rec = convertCharacter({ char: ch, pinyin, gloss }, data);
  const exportName = "fitted" + name[0].toUpperCase() + name.slice(1);
  writeFileSync(new URL(`../src/bihua/characters/fitted/${name}.ts`, import.meta.url),
    emitModule(rec, exportName));
  const oracleInk = polygonClipping.union(...data.strokes.map((d) => flattenPath(d)));
  const bake = bakeCharacter(rec, maobiStyle);
  const inter = polygonClipping.intersection(bake.fused, oracleInk);
  const union = polygonClipping.union(bake.fused, oracleInk);
  const iou = multiPolygonArea(inter) / multiPolygonArea(union);
  const reviews = rec.strokes.filter((s) => s.fit?.review).length;
  totalStrokes += rec.strokes.length;
  reviewCount += reviews;
  failCount += rec.strokes.filter((s) => s.fit?.validator === "fail").length;
  rec.strokes.forEach((s, i) => {
    if (s.fit?.review) queue.push(`${ch} stroke ${i + 1}: ${s.form} (conf ${s.fit.confidence}, validator ${s.fit.validator}${s.fit.failedRelations ? "; failed " + s.fit.failedRelations.join(", ") : ""})`);
  });
  console.log(
    `${ch}    ${String(rec.strokes.length).padEnd(8)} ${iou.toFixed(3)}  ${String(reviews).padEnd(7)} ${rec.strokes.map((s) => s.form).join(" ")}`,
  );
}
console.log(`\n${BATCH.length} characters, ${totalStrokes} strokes; ${reviewCount} flagged for review, ${failCount} validator failures.`);
console.log("\nReview queue:");
for (const q of queue) console.log("  - " + q);
